export function resolveSystemPrompt(mode: EnhanceModeId, customPrompt: string): string {
  if (mode === "custom") {
    const trimmed = customPrompt.trim();
    return trimmed ? `${trimmed}\n\n${BASE_RULE}` : ENHANCE_MODES.clean.systemPrompt;
  }
  return ENHANCE_MODES[mode].systemPrompt;
}
