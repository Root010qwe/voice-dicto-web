export type EnhanceModeId = "clean" | "business" | "notes" | "custom";

export interface EnhanceModeDef {
  id: EnhanceModeId;
  label: string;
  description: string;
  systemPrompt: string;
}

const BASE_RULE =
  "Отвечай ТОЛЬКО итоговым текстом, без вступлений, пояснений, кавычек и комментариев от себя. Не придумывай факты, которых не было в исходном тексте. Сохраняй язык оригинала (русский).";

